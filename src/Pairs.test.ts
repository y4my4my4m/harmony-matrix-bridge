import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { ManagedPair } from './BridgeApi.js'
import { separateCheck, type BridgeCheck, type SeparateChecks } from './HarmonyClient.js'
import { HttpError } from './http.js'
import { PairManager, type PairManagerOptions } from './Pairs.js'
import { Store } from './Store.js'

const A = '22222222-2222-4222-8222-222222222222'
const B = '33333333-3333-4333-8333-333333333333'
const managers: PairManager[] = []
const stores: Store[] = []
beforeEach(() => { vi.useFakeTimers() })
afterEach(() => { managers.splice(0).forEach(manager => manager.stop()); stores.splice(0).forEach(store => store.close()); vi.useRealTimers() })

const spec = (overrides: Partial<ManagedPair> = {}): ManagedPair => ({ channelId: A, channelName: 'general', roomId: '!a:matrix.test', roomAlias: null,
  direction: 'both', senderMode: 'ghost', encrypted: false, ...overrides })
const gone = (status: number, errcode?: string) => new HttpError('refused', false, status, errcode)
const busy = (retryAfterMs?: number) => new HttpError('busy', true, retryAfterMs === undefined ? 503 : 429, undefined, retryAfterMs)

function setup(options: Partial<PairManagerOptions> = {}, store = new Store(':memory:')) {
  if (!stores.includes(store)) stores.push(store)
  const harmony = { check: vi.fn((channelId: string, userId?: string): Promise<BridgeCheck> => separateCheck({ ...harmony, bridgeRoom: harmony.room } as unknown as SeparateChecks, channelId, userId)),
    room: vi.fn().mockResolvedValue({ room_id: null, sender_mode: 'ghost' }), requireMatrixBridge: vi.fn().mockResolvedValue(undefined), channelIsPlaintext: vi.fn().mockResolvedValue(true),
    bridgeRoom: vi.fn().mockImplementation(async (_channel: string, initial?: { room_id: string }) => ({ room_id: initial!.room_id, sender_mode: 'ghost' })) }
  const matrix = { resolveAlias: vi.fn().mockResolvedValue({ roomId: '!resolved:matrix.test', servers: ['matrix.test', 'other.test'] }),
    membership: vi.fn().mockResolvedValue(null), joinRoom: vi.fn().mockResolvedValue(undefined), roomIsPlaintext: vi.fn().mockResolvedValue(true), canSend: vi.fn().mockResolvedValue(true) }
  const events = { onPairs: vi.fn(), onReady: vi.fn(), onRemoved: vi.fn(), onStale: vi.fn(), report: vi.fn() }
  const manager = new PairManager({ harmony, matrix, store, ghosts: true, ...events, ...options })
  managers.push(manager)
  const settle = () => vi.advanceTimersByTimeAsync(0)
  return { manager, harmony, matrix, store, settle, ...events }
}

describe('PairManager', () => {
  it('joins, checks and binds a room, in that order, and calls it ready only then', async () => {
    const { manager, harmony, matrix, settle, onReady } = setup()
    const order: string[] = []
    const note = (name: string, value: unknown) => async () => { order.push(name); return value as never }
    harmony.requireMatrixBridge.mockImplementation(note('registered', undefined))
    harmony.channelIsPlaintext.mockImplementation(note('harmony plaintext', true))
    matrix.joinRoom.mockImplementation(note('join', undefined))
    matrix.roomIsPlaintext.mockImplementation(note('matrix plaintext', true))
    harmony.bridgeRoom.mockImplementation(note('bind', { room_id: '!a:matrix.test', sender_mode: 'ghost' }))
    manager.apply([spec()])
    expect(manager.pairs).toMatchObject([{ harmonyChannelId: A, matrixRoomId: '!a:matrix.test', state: 'joining', direction: 'both', senderMode: 'ghost' }])
    expect(matrix.joinRoom).not.toHaveBeenCalled()
    manager.start()
    await settle()
    expect(order).toEqual(['registered', 'harmony plaintext', 'join', 'matrix plaintext', 'bind'])
    expect(harmony.bridgeRoom).toHaveBeenCalledExactlyOnceWith(A, { room_id: '!a:matrix.test', initial_sender_mode: 'ghost' })
    expect(manager.pairs[0].state).toBe('ready')
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'ready', error: null }])
    expect(onReady).toHaveBeenCalledExactlyOnceWith(A)
  })
  it('resolves an alias, joins through its servers and binds with the alias it resolved', async () => {
    const { manager, harmony, matrix, settle, store } = setup()
    store.saveInvite({ roomId: '!resolved:matrix.test', name: null, alias: null, encrypted: false })
    manager.apply([spec({ roomId: null, roomAlias: '#town:other.test' })])
    expect(manager.pairs).toEqual([])
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'joining', error: null }])
    manager.start()
    await settle()
    expect(matrix.resolveAlias).toHaveBeenCalledExactlyOnceWith('#town:other.test')
    expect(matrix.joinRoom).toHaveBeenCalledExactlyOnceWith('!resolved:matrix.test', ['matrix.test', 'other.test'])
    expect(harmony.bridgeRoom).toHaveBeenCalledExactlyOnceWith(A, { room_id: '!resolved:matrix.test', initial_sender_mode: 'ghost', room_alias: '#town:other.test' })
    expect(manager.pairs).toMatchObject([{ matrixRoomId: '!resolved:matrix.test', state: 'ready' }])
    expect(store.invites()).toEqual([])
    manager.apply([spec({ roomId: '!resolved:matrix.test', roomAlias: '#town:other.test' })])
    await settle()
    expect(manager.pairs[0].state).toBe('ready')
    expect(matrix.joinRoom).toHaveBeenCalledOnce()
  })
  it('reports one bad pair and runs the others', async () => {
    const { manager, matrix, settle } = setup()
    matrix.joinRoom.mockImplementation(async (room: string) => { if (room === '!a:matrix.test') throw gone(403, 'M_FORBIDDEN') })
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test' })])
    manager.start()
    await settle()
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'error', error: 'not_invited' }, { channel_id: B, state: 'ready', error: null }])
    expect(manager.pairs.map(pair => pair.state)).toEqual(['error', 'ready'])
    expect(manager.problems()).toEqual([{ code: 'room_not_joined', detail: '!a:matrix.test' }])
  })
  it('does not let a room that never answers hold up the others', async () => {
    const { manager, matrix, settle } = setup()
    matrix.joinRoom.mockImplementation((room: string) => room === '!a:matrix.test' ? new Promise(() => {}) : Promise.resolve())
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test' })])
    manager.start()
    await settle()
    expect(manager.reports().map(report => report.state)).toEqual(['joining', 'ready'])
  })
  it.each([
    ['channel_encrypted', (mocks: ReturnType<typeof setup>) => { mocks.harmony.channelIsPlaintext.mockResolvedValue(false) }],
    ['room_encrypted', (mocks: ReturnType<typeof setup>) => { mocks.matrix.roomIsPlaintext.mockResolvedValue(false) }],
    ['room_encrypted', (mocks: ReturnType<typeof setup>) => { mocks.store.acceptTransaction('x', [], ['!a:matrix.test']) }],
    ['harmony_not_bound', (mocks: ReturnType<typeof setup>) => { mocks.harmony.requireMatrixBridge.mockRejectedValue(gone(403)) }],
    ['harmony_not_bound', (mocks: ReturnType<typeof setup>) => { mocks.harmony.channelIsPlaintext.mockRejectedValue(gone(403)) }],
    ['harmony_not_bound', (mocks: ReturnType<typeof setup>) => { mocks.harmony.bridgeRoom.mockRejectedValue(gone(403)) }],
    ['room_in_use', (mocks: ReturnType<typeof setup>) => { mocks.harmony.bridgeRoom.mockRejectedValue(gone(409, 'room_in_use')) }],
    ['room_in_use', (mocks: ReturnType<typeof setup>) => { mocks.harmony.bridgeRoom.mockResolvedValue({ room_id: '!else:matrix.test', sender_mode: 'ghost' }) }],
    ['not_invited', (mocks: ReturnType<typeof setup>) => { mocks.matrix.membership.mockResolvedValue('ban') }],
    ['room_not_found', (mocks: ReturnType<typeof setup>) => { mocks.matrix.joinRoom.mockRejectedValue(gone(404)) }],
  ] as const)('refuses with %s and relays nothing (%#)', async (code, arrange) => {
    const mocks = setup()
    arrange(mocks)
    mocks.manager.apply([spec()])
    mocks.manager.start()
    await mocks.settle()
    expect(mocks.manager.reports()).toEqual([{ channel_id: A, state: 'error', error: code }])
    expect(mocks.manager.pairs[0].state).toBe('error')
    expect(mocks.onReady).not.toHaveBeenCalled()
  })
  it('joins no room it knows to be encrypted, and none for an encrypted channel', async () => {
    const { manager, matrix, harmony, store, settle } = setup()
    store.acceptTransaction('x', [], ['!a:matrix.test'])
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test', encrypted: true })])
    manager.start()
    await settle()
    expect(matrix.joinRoom).not.toHaveBeenCalled()
    expect(manager.reports().map(report => report.error)).toEqual(['room_encrypted', 'channel_encrypted'])
    expect(harmony.bridgeRoom).not.toHaveBeenCalled()
  })
  it('reports an unknown alias and tries again later', async () => {
    const { manager, matrix, settle } = setup()
    matrix.resolveAlias.mockRejectedValueOnce(gone(404, 'M_NOT_FOUND'))
    manager.apply([spec({ roomId: null, roomAlias: '#town:other.test' })])
    manager.start()
    await settle()
    expect(manager.reports()[0].error).toBe('room_not_found')
    expect(manager.problems()).toEqual([{ code: 'room_not_joined', detail: '#town:other.test' }])
    await vi.advanceTimersByTimeAsync(16_000)
    expect(manager.reports()[0]).toEqual({ channel_id: A, state: 'ready', error: null })
  })
  it('keeps relaying where it may not send, and says so', async () => {
    const { manager, matrix, settle, onReady } = setup()
    matrix.canSend.mockResolvedValue(false)
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test', direction: 'to_harmony' })])
    manager.start()
    await settle()
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'error', error: 'cannot_send' }, { channel_id: B, state: 'ready', error: null }])
    expect(manager.pairs.map(pair => pair.state)).toEqual(['ready', 'ready'])
    expect(onReady).toHaveBeenCalledTimes(2)
    expect(matrix.canSend).toHaveBeenCalledExactlyOnceWith('!a:matrix.test')
  })
  it('reports refused ghosts beside a relaying pair until one works', async () => {
    const { manager, settle } = setup()
    manager.apply([spec()])
    manager.start()
    await settle()
    manager.noteGhosts(A, false)
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'error', error: 'ghosts_unavailable' }])
    expect(manager.pairs[0].state).toBe('ready')
    manager.noteGhosts(A, true)
    expect(manager.reports()[0].error).toBeNull()
    manager.noteGhosts('unknown', false)
  })
  it('binds as relay and reports no ghosts for an ordinary account', async () => {
    const { manager, harmony, settle } = setup({ ghosts: false })
    manager.apply([spec()])
    manager.start()
    await settle()
    expect(harmony.bridgeRoom.mock.calls[0][1].initial_sender_mode).toBe('relay')
    expect(manager.pairs[0].senderMode).toBe('relay')
    manager.noteGhosts(A, false)
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'ready', error: null }])
  })
  it('keeps a relaying pair through outages and a joining one waiting, spacing its attempts', async () => {
    const { manager, matrix, harmony, settle } = setup()
    manager.apply([spec()])
    manager.start()
    await settle()
    matrix.membership.mockResolvedValue('join')
    harmony.requireMatrixBridge.mockRejectedValue(busy())
    await vi.advanceTimersByTimeAsync(6 * 60_000)
    expect(manager.pairs[0].state).toBe('ready')
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test' })])
    harmony.requireMatrixBridge.mockClear()
    harmony.requireMatrixBridge.mockRejectedValue(busy(90_000))
    await vi.advanceTimersByTimeAsync(80_000)
    expect(harmony.requireMatrixBridge.mock.calls.filter(call => call[0] === B).length).toBeLessThanOrEqual(1)
    expect(manager.reports()[1]).toEqual({ channel_id: B, state: 'joining', error: null })
    harmony.requireMatrixBridge.mockResolvedValue(undefined)
    await vi.advanceTimersByTimeAsync(5 * 60_000)
    expect(manager.reports().map(report => report.state)).toEqual(['ready', 'ready'])
  })
  it.each(['requireMatrixBridge', 'bridgeRoom', 'membership', 'joinRoom', 'resolveAlias'] as const)('learns nothing from a refused token (%s)', async call => {
    const { manager, matrix, harmony, settle, report } = setup()
    const mock = call in harmony ? harmony[call as 'bridgeRoom'] : matrix[call as 'joinRoom']
    mock.mockRejectedValue(gone(401, 'M_UNKNOWN_TOKEN'))
    manager.apply([spec(call === 'resolveAlias' ? { roomId: null, roomAlias: '#town:matrix.test' } : {})])
    manager.start()
    await settle()
    expect(manager.reports()).toEqual([{ channel_id: A, state: 'joining', error: null }])
    expect(report).not.toHaveBeenCalled()
  })
  it('stops relaying when a later check finds the room or channel encrypted or the binding gone', async () => {
    for (const change of ['room', 'channel', 'binding', 'kicked']) {
      const { manager, matrix, harmony, settle } = setup()
      manager.apply([spec()])
      manager.start()
      await settle()
      expect(manager.pairs[0].state).toBe('ready')
      matrix.membership.mockResolvedValue(change === 'kicked' ? 'leave' : 'join')
      if (change === 'room') matrix.roomIsPlaintext.mockResolvedValue(false)
      if (change === 'channel') harmony.channelIsPlaintext.mockResolvedValue(false)
      if (change === 'binding') harmony.requireMatrixBridge.mockRejectedValue(gone(403))
      await vi.advanceTimersByTimeAsync(10 * 60_000 + 1000)
      expect(manager.pairs[0].state, change).toBe('error')
      expect(matrix.joinRoom).toHaveBeenCalledOnce()
    }
  })
  it('checks a room at once when its encryption is turned on', async () => {
    const { manager, matrix, settle } = setup()
    manager.apply([spec()])
    manager.start()
    await settle()
    matrix.membership.mockResolvedValue('join')
    matrix.roomIsPlaintext.mockResolvedValue(false)
    manager.noteEncrypted('!a:matrix.test')
    await settle()
    expect(manager.reports()[0].error).toBe('room_encrypted')
  })
  it('tells a channel without a binding from an encrypted one', async () => {
    const { manager, harmony, settle } = setup()
    harmony.check.mockResolvedValue({ registered: false, roomId: null, mode: null, plaintext: false, relayAllowed: false, member: null })
    manager.apply([spec()])
    manager.start()
    await settle()
    expect(manager.reports()[0].error).toBe('harmony_not_bound')
  })
  it('checks a pair at once whose refresh was refused', async () => {
    const { manager, harmony, matrix, settle } = setup()
    manager.apply([spec()])
    manager.start()
    await settle()
    matrix.membership.mockResolvedValue('join')
    harmony.channelIsPlaintext.mockResolvedValue(false)
    manager.recheck(B)
    await settle()
    expect(manager.reports()[0].state).toBe('ready')
    manager.recheck(A)
    await settle()
    expect(manager.reports()[0].error).toBe('channel_encrypted')
  })
  it('checks an encrypted channel at once when the configuration says so', async () => {
    const { manager, settle } = setup()
    manager.apply([spec()])
    manager.start()
    await settle()
    manager.apply([spec({ encrypted: true })])
    await settle()
    expect(manager.reports()[0].error).toBe('channel_encrypted')
  })
  it('does not rejoin a room it was removed from until it is invited again, across restarts', async () => {
    const first = setup()
    first.manager.apply([spec()])
    first.manager.start()
    await first.settle()
    first.matrix.membership.mockResolvedValue('leave')
    first.manager.noteMembership('!a:matrix.test', 'leave')
    await first.settle()
    expect(first.manager.reports()[0].error).toBe('not_invited')
    expect(first.matrix.joinRoom).toHaveBeenCalledOnce()
    first.manager.stop()

    await vi.advanceTimersByTimeAsync(1000)
    const second = setup({}, first.store)
    second.matrix.membership.mockResolvedValue('leave')
    second.manager.apply([spec()])
    second.manager.start()
    await second.settle()
    expect(second.manager.reports()[0].error).toBe('not_invited')
    expect(second.matrix.joinRoom).not.toHaveBeenCalled()
    second.store.saveInvite({ roomId: '!a:matrix.test', name: null, alias: null, encrypted: false })
    second.manager.noteMembership('!a:matrix.test', 'invite')
    await second.settle()
    expect(second.matrix.joinRoom).toHaveBeenCalledOnce()
    expect(second.manager.reports()[0].error).toBeNull()
  })
  it('refetches the configuration on room_changed and lets an old check change nothing', async () => {
    const { manager, harmony, settle, onStale } = setup()
    harmony.bridgeRoom.mockRejectedValueOnce(gone(409, 'room_changed'))
    manager.apply([spec()])
    manager.start()
    await settle()
    expect(onStale).toHaveBeenCalledOnce()
    expect(manager.reports()[0]).toEqual({ channel_id: A, state: 'joining', error: null })
    let finish!: () => void
    harmony.requireMatrixBridge.mockImplementationOnce(() => new Promise<void>(resolve => { finish = resolve }))
    await vi.advanceTimersByTimeAsync(6_000)
    manager.apply([spec({ roomId: '!new:matrix.test' })])
    finish()
    await settle()
    expect(manager.pairs).toMatchObject([{ matrixRoomId: '!new:matrix.test' }])
    await vi.advanceTimersByTimeAsync(1_000)
    expect(manager.pairs).toMatchObject([{ matrixRoomId: '!new:matrix.test', state: 'ready' }])
  })
  it.each(['replaced', 'removed'])('joins and binds nothing more for a pair that was %s during its check', async how => {
    const { manager, harmony, matrix, settle } = setup()
    let finish!: () => void
    harmony.requireMatrixBridge.mockImplementationOnce(() => new Promise<void>(resolve => { finish = resolve }))
    manager.apply([spec()])
    manager.start()
    manager.apply(how === 'replaced' ? [spec({ roomId: '!new:matrix.test' })] : [])
    finish()
    await settle()
    expect(matrix.joinRoom.mock.calls.map(call => call[0])).toEqual(how === 'replaced' ? ['!new:matrix.test'] : [])
    expect(harmony.bridgeRoom.mock.calls.map(call => call[1].room_id)).toEqual(how === 'replaced' ? ['!new:matrix.test'] : [])
  })
  it('changes direction in place, replaces another room, and removes what is no longer named', async () => {
    const { manager, settle, onRemoved, onReady } = setup()
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test' })])
    manager.start()
    await settle()
    manager.apply([spec({ direction: 'to_matrix' }), spec({ channelId: B, roomId: '!c:matrix.test' })])
    expect(manager.pairs[0]).toMatchObject({ direction: 'to_matrix', state: 'ready' })
    expect(onRemoved).toHaveBeenCalledExactlyOnceWith(B)
    await settle()
    expect(manager.pairs[1]).toMatchObject({ matrixRoomId: '!c:matrix.test', state: 'ready' })
    expect(manager.keepsGhosts('!b:matrix.test')).toBe(false)
    expect(manager.keepsGhosts('!c:matrix.test')).toBe(true)
    manager.apply([])
    expect(manager.pairs).toEqual([])
    expect(onRemoved).toHaveBeenCalledTimes(3)
    expect(onReady).toHaveBeenCalledTimes(3)
    expect(manager.keepsGhosts('!c:matrix.test')).toBe(false)
  })
  it('keeps every room\'s ghosts while an alias may still name it', async () => {
    const { manager, matrix, settle } = setup()
    matrix.resolveAlias.mockRejectedValueOnce(busy()).mockRejectedValue(gone(404))
    manager.apply([spec({ roomId: null, roomAlias: '#town:other.test' })])
    manager.start()
    await settle()
    expect(manager.keepsGhosts('!any:matrix.test')).toBe(true)
    await vi.advanceTimersByTimeAsync(6_000)
    expect(manager.reports()[0].error).toBe('room_not_found')
    expect(manager.keepsGhosts('!any:matrix.test')).toBe(false)
  })
  it('sends the ghosts of a pair in error away, not those of one that only cannot send', async () => {
    const { manager, matrix, settle } = setup()
    matrix.canSend.mockResolvedValue(false)
    matrix.roomIsPlaintext.mockImplementation(async (room: string) => room !== '!b:matrix.test')
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test' })])
    manager.start()
    await settle()
    expect(manager.keepsGhosts('!a:matrix.test')).toBe(true)
    expect(manager.keepsGhosts('!b:matrix.test')).toBe(false)
  })
  it('does not pair one room twice', async () => {
    const { manager, matrix, settle } = setup()
    matrix.resolveAlias.mockResolvedValue({ roomId: '!a:matrix.test', servers: [] })
    manager.apply([spec(), spec({ channelId: B, roomId: null, roomAlias: '#same:matrix.test' })])
    manager.start()
    await settle()
    expect(manager.reports().map(report => report.error)).toEqual([null, 'room_in_use'])
  })
  it('remembers when a pair began, until it ends', async () => {
    const { manager, store } = setup()
    manager.apply([spec()])
    const since = manager.pairs[0].since!
    await vi.advanceTimersByTimeAsync(60_000)
    const restarted = setup({}, store)
    restarted.manager.apply([spec()])
    expect(restarted.manager.pairs[0].since).toBe(since)
    restarted.manager.apply([])
    restarted.manager.apply([spec()])
    expect(restarted.manager.pairs[0].since).toBe(since + 60_000)
  })
  it('follows the rooms it is in, and after a restart those it was in', async () => {
    const { manager, matrix, settle } = setup()
    manager.apply([spec(), spec({ channelId: B, roomId: '!b:matrix.test' })])
    expect(manager.joinedRooms()).toEqual([])
    expect(manager.joinedRooms(['!b:matrix.test', '!unpaired:matrix.test'])).toEqual(['!b:matrix.test'])
    manager.start()
    await settle()
    expect(manager.joinedRooms()).toEqual(['!a:matrix.test', '!b:matrix.test'])
    matrix.membership.mockResolvedValue('leave')
    manager.noteMembership('!b:matrix.test', 'leave')
    expect(manager.joinedRooms(['!b:matrix.test'])).toEqual(['!a:matrix.test'])
  })
})
